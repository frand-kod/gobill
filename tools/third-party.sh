#!/bin/sh
# Writes THIRD_PARTY_LICENSES.txt: the license texts of every Go module linked into cmd/gobill,
# then the web assets. Run it after changing go.mod or web/static/vendor. The file is embedded in
# the binary and served at /licenses, so it must ship with every build.
set -eu
cd "$(dirname "$0")/.."
go mod download
{
	echo "Third-party licenses for gobill. Generated by tools/third-party.sh; do not edit by hand."
	echo
	echo "== Go modules linked into cmd/gobill =="
	go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/gobill |
		sort -u | while read -r path ver dir; do
			[ -n "$dir" ] || continue
			echo
			echo "--- $path $ver ---"
			find "$dir" -maxdepth 1 -type f \( -iname 'LICEN*' -o -iname 'COPYING*' -o -iname 'NOTICE*' \) | sort |
				while read -r f; do cat "$f"; echo; done
		done
	echo
	echo "== Web assets: web/static/vendor and web/static/icons =="
	echo
	cat web/static/vendor/LICENSES.txt
	echo
	cat web/static/icons/LICENSE
} > THIRD_PARTY_LICENSES.txt
echo "wrote THIRD_PARTY_LICENSES.txt ($(wc -c < THIRD_PARTY_LICENSES.txt) bytes)"
